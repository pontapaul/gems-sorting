let currentLang = "en";

function t(key, params = {}) {
  const value = (MESSAGES[currentLang] && MESSAGES[currentLang][key]) ?? MESSAGES.en[key] ?? key;
  return typeof value === "function" ? value(params) : value;
}

/** Translates the static page: data-i18n (text), data-i18n-html (trusted markup) and attributes. */
function applyI18n(lang) {
  currentLang = MESSAGES[lang] ? lang : "en";
  document.documentElement.lang = currentLang;
  document.title = t("title");
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const [attr, name] of [["i18nPlaceholder", "placeholder"], ["i18nTitle", "title"], ["i18nAria", "aria-label"]]) {
    for (const el of document.querySelectorAll(`[data-${attr.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}]`)) {
      el.setAttribute(name, t(el.dataset[attr]));
    }
  }
  document.documentElement.style.setProperty("--drop-here", JSON.stringify(t("group.dropHere")));
}
